public class Operators {
    public static void main(String[] args) {
//       Addition

        int a = 15;
        int b = 69;
        System.out.println(a+b);
//        subtraction

        int x = 1;
        int y = 0;
        System.out.println(x-y);

//        Multiplying

        int j = 188;
        int k = 93;
        System.out.println(j*k);

//        Division

        int n = 2;
        int m = 10;
        System.out.println(n%m);
    }
}
